CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email VARCHAR(255) NOT NULL,
    pwdhash VARCHAR(255) NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    nickname VARCHAR(255) NULL,
    name VARCHAR(255) NULL,
    surname VARCHAR(255) NULL,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    -- Core sets updated_at explicitly when it updates a user.
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    PRIMARY KEY (id),
    CONSTRAINT users_email_unique UNIQUE (email)
);

CREATE TABLE auth_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    users_id BIGINT NOT NULL,
    jti VARCHAR(255) NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    released TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    expiration TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    revocation_time TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    PRIMARY KEY (id),
    CONSTRAINT auth_tokens_jti_unique UNIQUE (jti),
    CONSTRAINT auth_tokens_users_id_foreign
        FOREIGN KEY (users_id) REFERENCES users (id)
        ON DELETE CASCADE
);

CREATE INDEX auth_tokens_users_id_index ON auth_tokens (users_id);
CREATE INDEX auth_tokens_expiration_index ON auth_tokens (expiration);

CREATE TABLE email_verification_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    users_id BIGINT NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'UTC'),
    expiration TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL,
    used_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    PRIMARY KEY (id),
    CONSTRAINT email_verification_tokens_token_hash_unique UNIQUE (token_hash),
    CONSTRAINT email_verification_tokens_users_id_foreign
        FOREIGN KEY (users_id) REFERENCES users (id)
        ON DELETE CASCADE
);

CREATE INDEX email_verification_tokens_users_id_index ON email_verification_tokens (users_id);
